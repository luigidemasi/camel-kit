package io.github.luigidemasi.camelkit.doc;

public class GeneratedInfo {

    private String at;
    private String by;
    private String from;

    public GeneratedInfo() {
    }

    public GeneratedInfo(String at, String by, String from) {
        this.at = at;
        this.by = by;
        this.from = from;
    }

    public String getAt() {
        return at;
    }

    public void setAt(String at) {
        this.at = at;
    }

    public String getBy() {
        return by;
    }

    public void setBy(String by) {
        this.by = by;
    }

    public String getFrom() {
        return from;
    }

    public void setFrom(String from) {
        this.from = from;
    }
}
